<?php
/**
 * Файл инициализации соединения с базой данных
 * Использует настройки из config.php для создания объекта PDO.
 */

// Подключаем конфигурационный файл (путь относительно папки includes)
require_once __DIR__ . '/config.php';

try {
    // Формируем строку DSN на основе констант из Canvas
    $dsn = "mysql:host=" . DB_HOST . ";dbname=" . DB_NAME . ";charset=" . DB_CHARSET;

    // Настройки драйвера PDO
    $options = [
        // Режим выброса исключений при ошибках
        PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
        // Режим выборки данных по умолчанию (ассоциативный массив)
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        // Отключение эмуляции подготовленных запросов для повышения безопасности
        PDO::ATTR_EMULATE_PREPARES   => false,
    ];

    /**
     * Создаем экземпляр PDO
     * Теперь переменная $pdo доступна во всех API-скриптах,
     * где подключен данный файл.
     */
    $pdo = new PDO($dsn, DB_USER, DB_PASS, $options);

} catch (\PDOException $e) {
    /**
     * В случае ошибки соединения прекращаем выполнение и выводим сообщение.
     * Для защиты данных в продакшене лучше логировать ошибку,
     * а пользователю выводить нейтральное сообщение.
     */
    die("Ошибка подключения к базе данных: " . $e->getMessage());
}